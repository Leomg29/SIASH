"use strict";
const assert=require("node:assert/strict");
const {allowed,periodicity,hash,cpfValid,privacyFindings,validateDocsMutation}=require("../docs-governance-integrity.cjs");
assert.equal(allowed("reader","edit","UTIN","UTIN"),false);
assert.equal(allowed("editor","approve","UTIN","UTIN"),false);
assert.equal(allowed("validator","approve","UTIN","UTIN"),true);
assert.equal(allowed("validator","approve","UTIN","CTI"),false);
assert.equal(allowed("owner","approve","*","CTI"),true);
for(const m of [12,24,36])assert.equal(periodicity(m),m);
assert.throws(()=>periodicity(48),/INVALID_PERIOD/);
assert.equal(hash(Buffer.from("abc")),"ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
assert.equal(cpfValid("529.982.247-25"),true);
assert.equal(cpfValid("111.111.111-11"),false);
assert.deepEqual(privacyFindings("prontuário: 123456; data de nascimento: 01/01/2024").sort(),["NASCIMENTO","PRONTUARIO"]);
assert.deepEqual(privacyFindings("POP: Higienização das mãos. Referências ANVISA."),[]);
const old=[{id:"a",versions:[{revision:"01",createdAt:"t",workflow:"Vigente",wordKey:"old"}]}];
assert.equal(validateDocsMutation(old,[]).ok,false);
assert.equal(validateDocsMutation(old,[{id:"a",versions:[]}]).ok,false);
assert.equal(validateDocsMutation(old,[{id:"a",versions:[{revision:"01",createdAt:"t",workflow:"Vigente",wordKey:"new"}]}]).ok,false);
assert.equal(validateDocsMutation(old,[{id:"a",versions:[{revision:"01",createdAt:"t",workflow:"Vigente",wordKey:"old"},{revision:"02",workflow:"Vigente"}]}]).ok,false);
assert.equal(validateDocsMutation(old,[{id:"a",versions:[{revision:"01",createdAt:"t",workflow:"Vigente",wordKey:"old"},{revision:"02",workflow:"Em revisão"}]}]).ok,true);
const {scientificSourceUrl,scientificReferencesVerified}=require("../docs-governance-integrity.cjs");
assert.ok(scientificSourceUrl("https://portaldeboaspraticas.iff.fiocruz.br/atencao-recem-nascido/"));
assert.ok(scientificSourceUrl("https://pubmed.ncbi.nlm.nih.gov/123456/"));
assert.ok(scientificSourceUrl("https://www.gov.br/saude/pt-br"));
assert.equal(scientificSourceUrl("https://sbp.com.br.evil.example/"),null);
assert.equal(scientificSourceUrl("http://who.int/publications"),null);
assert.equal(scientificSourceUrl("https://www.gov.br/outro/"),null);
const evidence="https://www.sbp.com.br/documento-real";
assert.equal(scientificReferencesVerified([{title:"Documento científico",year:2025,url:evidence}],[evidence]),true);
assert.equal(scientificReferencesVerified([{title:"Documento científico",year:2025,url:evidence}],[]),false);
assert.equal(scientificReferencesVerified([{title:"Documento científico",year:2025,url:"https://fake.example/"}],["https://fake.example/"]),false);
